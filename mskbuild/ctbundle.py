"""Bundle the Computational Thinking Adventure's scripts and styles.

Every file in static/js/ct and static/css/ct is concatenated in file name
order, so the numeric prefixes (00-core, 01-store, ... 90-boot) set the order
the pieces load in. One request each, and only the adventure pages ask for them.
"""
import os


def bundle(root, ext):
    base = os.path.join(root, "static", ext, "ct")
    names = sorted(n for n in os.listdir(base) if n.endswith("." + ext))
    parts = ["/* MskProd Computational Thinking Adventure. Generated by build.py. */"]
    for name in names:
        with open(os.path.join(base, name), encoding="utf-8") as fh:
            parts.append("/* ---- %s ---- */" % name)
            parts.append(fh.read().strip())
    return "\n".join(parts) + "\n"


def sources(root):
    """Every source file, for the logic tests that run outside a browser."""
    base = os.path.join(root, "static", "js", "ct")
    return [os.path.join(base, n) for n in sorted(os.listdir(base)) if n.endswith(".js")]
